"""Self-selection: run several state programs on a case and let a critic keep one. Offline test on judged clips.

  python -I -X utf8 eval/pick_bench.py held [--model claude-sonnet-5-5]      # results/pick_held.json
  python -I -X utf8 eval/pick_bench.py dev

For every case the clips of each arm already exist and already have the benchmark judge's scores (held-out:
unmodified, objective in the prompt, final program, each judged twice in one blinded batch; development: unmodified
and final, judged once). A critic (Claude, a different model from the judge) is shown the clips' contact sheets
side by side with the fields the generator may read (caption, request, perspective, camera actions) and says
which clip it would keep. It never sees a judge score or the benchmark rubric, and the clip order is shuffled per
case. The result is the judge's score of the clip the critic kept: what the system would have scored had it
generated all the programs and shipped the critic's choice. Costs as many rollouts per case as there are arms.
"""
import argparse
import base64
import io
import json
import random
import re
import statistics as st
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import requests
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "eval"))
sys.path.insert(0, str(ROOT / "tools"))
import full_v2 as f2  # noqa: E402
import llm  # noqa: E402

SYSTEM = ("You compare videos generated by a world model for the same scene and request. Each clip is shown as contact "
          "sheets: frames in time order, left to right, top to bottom, sheet after sheet. Be strict and literal. "
          "Reply with one JSON object and nothing else.")
ASK = """Scene at the start: {caption}
What was requested: {request}
Viewpoint: {perspective}
Camera actions commanded, in order: {action}

Which clip should be kept? Judge, in this order of importance:
1. Does the camera do what was commanded (the turns, walks, sideways steps, pauses, and the return if one was asked)?
   A clip where the camera stays still, keeps turning, or never comes back when it should have fails this.
2. For a request about a subject (a person, animal, vehicle): does the subject visibly carry it out?
3. When the camera returns to a view it left, is it the same place with the same things in it?
4. Do things keep moving and progressing plausibly, with real accumulated change, rather than a frozen picture, a
   motion repeated in place, or objects melting and morphing?
5. Do subjects and objects keep their identity, and is the picture clean?
Reply with JSON: {{"keep": one of {labels}, "ranking": [labels from best to worst], "why": one sentence}}"""


def block(path, width):
    im = Image.open(path).convert("RGB")
    im = im.resize((width, int(im.height * width / im.width)))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=80)
    return {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg",
                                        "data": base64.b64encode(buf.getvalue()).decode()}}


def ask(content, model):
    last = ""
    for k in range(4):
        try:
            r = requests.post("https://api.anthropic.com/v1/messages", timeout=180,
                              headers={"x-api-key": llm._key(), "anthropic-version": "2023-06-01"},
                              json={"model": model, "max_tokens": 300, "system": SYSTEM,
                                    "messages": [{"role": "user", "content": content}]})
            last = r.json()["content"][0]["text"]
            return json.loads(re.search(r"\{.*\}", last, re.S).group(0))
        except Exception as e:
            last = repr(e)[:200] + " " + str(getattr(r, "text", ""))[:200] if "r" in dir() else repr(e)[:200]
            time.sleep(3 + 4 * k)
    return {"error": last}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("split", choices=["held", "dev"])
    ap.add_argument("--model", default="claude-sonnet-5-5")
    ap.add_argument("--width", type=int, default=880)
    ap.add_argument("--sheets", type=int, default=6)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    if a.split == "held":
        per = json.loads((ROOT / "results" / "held_out.json").read_text())["per_case"]
        arms, inp = ["baseline", "objective", "final"], {x: ROOT / "runs" / "jin_held" / x for x in ("baseline", "objective", "final")}
    else:
        per = json.loads((ROOT / "results" / "dev_half.json").read_text())["per_case"]
        arms, inp = ["baseline", "final"], {"baseline": ROOT / "runs" / "jin_half1" / "lingbot2_14b_open",
                                            "final": ROOT / "runs" / "jin_dev" / "final"}
        if not inp["baseline"].exists():
            inp["baseline"] = ROOT / "runs" / "jin_dev" / "baseline"
    score = {x: {c: st.mean(v) for c, v in per[x].items()} for x in arms}
    cases = {}
    for sp in ("gc", "if", "insight", "outsight"):
        for c in json.loads((ROOT / "third_party" / "pw_data" / sp / "data.json").read_text(encoding="utf8")):
            cases[c["task_id"]] = c
    todo = sorted(c for c in set.intersection(*[set(score[x]) for x in arms])
                  if all((inp[x] / c / "sheets" / "primary").exists() for x in arms))
    if a.limit:
        todo = todo[:a.limit]
    print(len(todo), "cases,", arms)

    def one(t):
        rng = random.Random("pick" + t)
        order = arms[:]
        rng.shuffle(order)
        labels = [chr(65 + i) for i in range(len(order))]
        content = []
        for lab, arm in zip(labels, order):
            sheets = sorted((inp[arm] / t / "sheets" / "primary").glob("*.jpg"))
            if len(sheets) > a.sheets:
                idx = [round(i * (len(sheets) - 1) / (a.sheets - 1)) for i in range(a.sheets)]
                sheets = [sheets[i] for i in sorted(set(idx))]
            content.append({"type": "text", "text": f"Clip {lab} ({len(sheets)} sheets):"})
            content += [block(s, a.width) for s in sheets]
        c = cases[t]
        content.append({"type": "text", "text": ASK.format(caption=c.get("image_caption", ""), request=c.get("prompt", ""),
                                                           perspective=c.get("perspective", "") or "unknown",
                                                           action=c.get("action", ""), labels=labels)})
        v = ask(content, a.model)
        keep = dict(zip(labels, order)).get(str(v.get("keep", "")).strip().upper()[:1])
        return t, {"order": order, "keep": keep, "why": str(v.get("why", v.get("error", "")))[:200]}

    with ThreadPoolExecutor(6) as ex:
        picks = dict(ex.map(one, todo))
    failed = [t for t, p in picks.items() if p["keep"] is None]
    picked = {t: score[p["keep"] or "final"][t] for t, p in picks.items()}
    fin = {t: score["final"][t] for t in todo}
    base = {t: score["baseline"][t] for t in todo}
    best = {t: max(score[x][t] for x in arms) for t in todo}
    hit = sum(1 for t in todo if picked[t] >= best[t] - 1e-9)
    out = {"split": a.split, "model": a.model, "arms": arms, "cases": len(todo), "critic_failed": failed,
           "kept": {x: sum(1 for p in picks.values() if p["keep"] == x) for x in arms},
           "kept_the_best_scoring_clip": hit, "tables": {"unmodified": f2.table(base), "final": f2.table(fin),
                                                         "critic_pick": f2.table(picked), "oracle_pick": f2.table(best)},
           "pick_minus_final": f2.paired(fin, picked), "pick_minus_unmodified": f2.paired(base, picked), "picks": picks}
    (ROOT / "results" / f"pick_{a.split}{a.tag}.json").write_text(json.dumps(out, indent=1))
    for k, t in out["tables"].items():
        print(k, {d: t[d] for d in ("GC", "IF", "IE", "OE", "overall")})
    print("kept", out["kept"], "best-scoring kept", hit, "of", len(todo), "failed", len(failed))
    print("pick - final", out["pick_minus_final"])
    print("pick - unmodified", out["pick_minus_unmodified"])

"""In-loop critic: looks at a finished rollout and says what went wrong.

The critic sees only what the generator may see: the case's caption, objective and
perspective, plus frames of the rollout itself. It never sees the benchmark's rubric
or a judge's score. Its verdict drives the repair loop in `repair.py`: which state
write to change and in which direction.

  verdict = critic.review(frames, caption, objective, perspective)
  -> {"action": 0..2, "subject": 0..2, "picture": 0..2, "alive": 0..2, "note": str, "score": float}

    action   2 the objective was visibly carried out, 1 started or partial, 0 not at all
    subject  2 the main subject / first-person vehicle stayed the same, 1 drifted, 0 lost or replaced
    picture  2 clean, 1 colour cast or visible artifacts, 0 collapsed (noise, blank, melted)
    alive    2 the world moves plausibly, 1 partly frozen or repetitive, 0 frozen
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools"))

SYSTEM = (
    "You inspect a video generated by a world model and report defects. You are shown frames sampled evenly "
    "in time, left to right, top to bottom, in two images (first half, second half). Be strict and literal: "
    "judge only what the frames show. Reply with one JSON object and nothing else.")

ASK = """Scene at the start: {caption}
What was requested: {objective}
Viewpoint: {perspective}

Rate each item 0, 1 or 2.
- "action": was the request visibly carried out by the end? 2 = yes, clearly (the subject reaches / enters / climbs /
  crosses what was asked, or the requested camera motion and return happened). 1 = started or partial. 0 = no:
  the subject stays where it was, moves the wrong way, or nothing relevant happens. For "wait and observe"
  requests, rate whether the scene keeps evolving in a meaningful way.
- "subject": does the main subject (the person, animal, vehicle, or the first-person vehicle interior) stay the
  same individual with the same clothing, colours and shape? 2 = yes. 1 = noticeable drift or stretching.
  0 = it disappears, is replaced, duplicated or morphs into something else.
- "picture": 2 = clean. 1 = colour cast, tint that grows over time, or visible artifacts. 0 = collapsed into noise,
  blank or melted frames.
- "alive": 2 = things move plausibly. 1 = partly frozen or repeating in place. 0 = a frozen picture.
Also give "note": one short sentence naming the single worst defect.
JSON keys: action, subject, picture, alive, note."""


def sheets(frames, n=12, cols=3, width=384):
    """Two contact sheets (first half, second half), n frames in total."""
    from PIL import Image
    idx = np.linspace(0, len(frames) - 1, n).astype(int)
    out = []
    for part in (idx[:n // 2], idx[n // 2:]):
        ims = [Image.fromarray(np.asarray(frames[i])).convert("RGB") for i in part]
        h = int(ims[0].height * width / ims[0].width)
        rows = (len(ims) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * width, rows * h))
        for j, im in enumerate(ims):
            sheet.paste(im.resize((width, h)), ((j % cols) * width, (j // cols) * h))
        out.append(sheet)
    return out


def total(v):
    """One number for ranking attempts. Losing the picture or the subject outweighs the rest."""
    return float(1.5 * v["action"] + 1.5 * v["subject"] + 1.0 * v["picture"] + 1.0 * v["alive"])


def review(frames, caption, objective, perspective="", model=None):
    import llm
    s = sheets(frames)
    v = llm.ask_json(SYSTEM, ASK.format(caption=caption, objective=objective, perspective=perspective or "unknown"),
                     images=[np.asarray(x) for x in s], max_tokens=300, model=model)
    out = {k: int(max(0, min(2, int(v.get(k, 1))))) for k in ("action", "subject", "picture", "alive")}
    out["note"] = str(v.get("note", ""))[:200]
    out["score"] = total(out)
    return out
